export const getCourse = (slug: string) => courses.find((course) => course.slug === slug);

export const getEntry = (courseSlug: string, entrySlug: string) => {
  const course = getCourse(courseSlug);
  return course ? { course, entry: course.entries.find((item) => item.slug === entrySlug) } : undefined;
};

/** Every entry across all folders, newest first — used by the vlog strip. */
export const latestEntries = () =>
  courses
    .flatMap((course) => course.entries.map((entry) => ({ course, entry })))
    .sort((a, b) => (a.entry.date < b.entry.date ? 1 : -1));
