export type Entry = {
  id: string; // "001-01" — also the photo slot: public/photos/entry-001-01.jpg
  slug: string;
  title: string;
  date: string; // ISO, used for "latest entries" ordering
  dateLabel: string; // shown on cards and entries
  about: string; // one-line lede
  description: string; // main write-up
  keyPoints: string[];
  notes: string[];
  task: string;
  wrapUp: string;
};

